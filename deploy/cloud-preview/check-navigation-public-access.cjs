'use strict';
// Fresh guest contexts only; existing authorized login is checked without saving a profile.
const fs=require('fs'),assert=require('assert');
const {chromium}=require(process.env.OMINDOS_PLAYWRIGHT||'playwright');
const base=process.env.CHECK_PREVIEW_URL||'https://cloud.omindos.cn/';
const out=process.env.CHECK_OUTPUT,creds=JSON.parse(fs.readFileSync(process.env.CHECK_AUTH_FILE));
const report={base,checks:[],page_errors:[]};let browser,page;
fs.mkdirSync(out,{recursive:true});
(async()=>{try{
 browser=await chromium.launch({executablePath:'/usr/bin/google-chrome',headless:true,
  args:['--no-sandbox','--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
 const a=await browser.newContext({viewport:{width:1440,height:1000}}),b=await browser.newContext();
 const pass=name=>{report.checks.push(name);console.log('PASS '+name);};
 page=await a.newPage();page.setDefaultTimeout(15000);
 page.on('pageerror',e=>report.page_errors.push(String(e)));
 await page.goto(base,{waitUntil:'domcontentloaded'});
 await page.waitForFunction(()=>!!profile&&!!currentPose&&!operation&&readyRevision===revision&&sceneEngine?.meshStats.loaded===20,null,{timeout:60000});
 await b.request.get(base+'v1/workbench-state');
 const ca=(await a.cookies()).find(c=>c.name==='__Secure-omindos-guest');
 const cb=(await b.cookies()).find(c=>c.name==='__Secure-omindos-guest');
 assert(ca&&cb&&ca.value!==cb.value);
 assert(ca.secure&&ca.httpOnly&&ca.sameSite==='Lax'&&ca.path==='/');
 pass('guest cookies remain distinct, Secure, HttpOnly, Lax and root scoped');
 const start=page.waitForResponse(r=>r.url().endsWith('/v1/navigation-start')&&r.request().method()==='POST');
 await page.click('.cloud-layout-tabs [data-panel=navigation]');
 await page.fill('#navigation-x','.55');await page.fill('#navigation-y','0');await page.fill('#navigation-yaw','0');
 await page.click('#navigation-run');const task=(await (await start).json()).task_id;assert(task);
 await page.waitForFunction(()=>!operation&&!navigationJob&&navigationData?.parking_confirmed,null,{timeout:30000});
 assert.equal((await a.request.get(base+'v1/navigation-heartbeat/'+task)).status(),200);
 assert.equal((await b.request.get(base+'v1/navigation-heartbeat/'+task)).status(),404);
 assert.equal((await b.request.get(base+'v1/navigation-task/'+task)).status(),404);
 pass('own task heartbeat succeeds; another guest cannot read heartbeat or full task');
 assert.equal((await b.request.post(base+'v1/navigation-cancel',{data:{task_id:task}})).status(),400);
 assert.equal((await (await a.request.get(base+'v1/navigation-heartbeat/'+task)).json()).status,'parked');
 pass('another guest cannot cancel the completed task or change its parked result');
 await page.click('#stage-stop');await page.waitForFunction(()=>emergencyStop&&!safetyPending&&!operation);
 assert.equal((await (await b.request.get(base+'v1/workbench-state')).json()).emergency_stop,false);
 await page.click('#reset-stop');await page.waitForFunction(()=>!emergencyStop&&!safetyPending);
 pass('guest A estop does not stop guest B; A reset succeeds');
 assert.equal((await b.request.post(base+'v1/workbench-active-profile',{data:{}})).status(),401);
 assert.equal((await b.request.get(base+'v1/navigation-heartbeat/missing',{headers:{Origin:'https://foreign.invalid'}})).status(),403);
 pass('guest configuration write still requires login and foreign-origin heartbeat is rejected');
 assert.equal((await b.request.get(base+'_navigation-preview/v1/workbench-state')).status(),401);
 pass('protected navigation candidate remains inaccessible to a public guest');
 const c=await browser.newContext();const login=await c.newPage();login.setDefaultTimeout(15000);
 await login.goto(base+'login',{waitUntil:'domcontentloaded'});
 await login.fill('#username',creds.username);await login.fill('#password',creds.password);
 await Promise.all([login.waitForURL(url=>url.pathname==='/'),login.click('button[type=submit]')]);
 const session=(await c.cookies()).find(cookie=>cookie.name==='__Secure-omindos-preview');
 assert(session&&session.path==='/'&&session.secure&&session.httpOnly&&session.sameSite==='Strict');
 assert.equal((await c.request.get(base+'v1/workbench-state')).status(),200);
 pass('existing form login and Secure HttpOnly Strict session access remain available');
 await c.close();
 assert.deepStrictEqual(report.page_errors,[]);report.status='passed';
 await page.screenshot({path:out+'/guest-isolation.png'});
}catch(e){report.status='failed';report.error=String(e).split(creds.password).join('[REDACTED]').replace(/Authorization[^\r\n]*/gi,'Authorization: [REDACTED]');process.exitCode=1;
 if(page)await page.screenshot({path:out+'/failure.png'}).catch(()=>{});
}finally{fs.writeFileSync(out+'/report.json',JSON.stringify(report,null,2));if(browser)await browser.close();console.log(JSON.stringify(report,null,2));}})();
